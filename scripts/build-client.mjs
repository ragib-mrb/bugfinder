// Bundles the two browser scripts into string modules, so they ship inside the package.
import { readFile, rm, writeFile } from 'node:fs/promises';
import { build } from 'tsup';

const outDir = '.client-build';
const bundles = [
  { entry: 'src/client/client.ts', name: 'client', out: 'src/client/bundle.generated.ts' },
  { entry: 'src/ui/app.ts', name: 'app', out: 'src/ui/app.generated.ts' },
];

for (const b of bundles) {
  await build({
    entry: { [b.name]: b.entry },
    format: ['iife'],
    outDir,
    minify: true,
    target: 'es2020',
    platform: 'browser',
    silent: true,
    dts: false,
    sourcemap: false,
    clean: false,
    config: false,
  });
  const code = await readFile(`${outDir}/${b.name}.global.js`, 'utf8');
  await writeFile(
    b.out,
    `// Generated by scripts/build-client.mjs. Do not edit.\nexport default ${JSON.stringify(code.trim())};\n`,
  );
}
await rm(outDir, { recursive: true, force: true });
